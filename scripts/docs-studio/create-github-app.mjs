#!/usr/bin/env node
// Creates the Docs Studio GitHub App through the GitHub App manifest flow.
// Dry-run by default: --apply is required to start the flow (which creates an
// App in your organization after you confirm it in the browser).
import crypto from 'node:crypto';
import fs from 'node:fs';
import http from 'node:http';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';
import { fail, parseCli, run } from './lib.mjs';

const REPO_ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '../..',
);
const DEFAULT_OUT = path.join(
  REPO_ROOT,
  'github-app-docs-studio-credentials.yaml',
);

const HELP = `Usage: node scripts/docs-studio/create-github-app.mjs --org <org> [options]

Creates a private GitHub App for Docs Studio using the manifest flow.

Options:
  --org <org>      Organization that will own the App (required).
  --name <name>    App name. Default: "Docs Studio (local)".
  --homepage <url> Homepage URL of the App. Default: http://localhost:3000
  --port <n>       Local callback port on 127.0.0.1. Default: random free port.
  --out <file>     Credentials file to write. Default: ./github-app-docs-studio-credentials.yaml
                   (gitignored; written with mode 0600).
  --force          Overwrite --out if it exists.
  --no-open        Print the local URL instead of opening a browser.
  --apply          Start the flow. WITHOUT it this is a dry-run that only prints
                   the manifest. Registering the App is a change in GitHub.
  -h, --help       Show this help.

Flow: a local server on 127.0.0.1 serves a page that POSTs the manifest to
https://github.com/organizations/<org>/settings/apps/new. You confirm in the
browser, GitHub redirects back to the local server with a temporary code, the
script exchanges it (POST /app-manifests/{code}/conversions) and writes the
credentials file. Secrets are never printed.

App permissions: contents:write, pull_requests:write, statuses:write,
metadata:read. No webhook events (hook is inactive).`;

const args = parseCli(
  {
    org: { type: 'string' },
    name: { type: 'string' },
    homepage: { type: 'string' },
    port: { type: 'string' },
    out: { type: 'string' },
    force: { type: 'boolean' },
    'no-open': { type: 'boolean' },
    apply: { type: 'boolean' },
  },
  HELP,
);

if (!args.org) fail('--org <org> is required (see --help).');
const org = args.org;
const appName = args.name ?? 'Docs Studio (local)';
const homepage = args.homepage ?? 'http://localhost:3000';
const outFile = path.resolve(args.out ?? DEFAULT_OUT);

const buildManifest = port => ({
  name: appName,
  url: homepage,
  public: false,
  redirect_url: `http://127.0.0.1:${port}/callback`,
  hook_attributes: { url: 'https://example.invalid/webhook', active: false },
  default_permissions: {
    contents: 'write',
    pull_requests: 'write',
    statuses: 'write',
    metadata: 'read',
  },
  default_events: [],
});

if (!args.apply) {
  console.log(
    '[dry-run] No App will be created. Manifest that would be submitted:\n',
  );
  console.log(JSON.stringify(buildManifest(args.port ?? '<port>'), null, 2));
  console.log(
    `\nTarget: https://github.com/organizations/${org}/settings/apps/new`,
  );
  console.log(`Credentials would be written to: ${outFile}`);
  console.log('\nRe-run with --apply to start the flow.');
  process.exit(0);
}

if (fs.existsSync(outFile) && !args.force) {
  fail(`${outFile} already exists. Use --force to overwrite it.`);
}

const state = crypto.randomBytes(24).toString('hex');
const escapeHtml = value =>
  value.replace(
    /[&<>"']/g,
    c =>
      ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[
        c
      ]),
  );

function safeEqual(a, b) {
  const left = Buffer.from(a);
  const right = Buffer.from(b);
  return left.length === right.length && crypto.timingSafeEqual(left, right);
}

async function exchange(code) {
  const response = await fetch(
    `https://api.github.com/app-manifests/${encodeURIComponent(
      code,
    )}/conversions`,
    {
      method: 'POST',
      headers: {
        Accept: 'application/vnd.github+json',
        'X-GitHub-Api-Version': '2022-11-28',
        'User-Agent': 'docs-studio-setup',
      },
    },
  );
  if (!response.ok) {
    throw new Error(
      `GitHub answered ${response.status} to the manifest conversion`,
    );
  }
  return response.json();
}

function writeCredentials(app) {
  const credentials = {
    appId: app.id,
    clientId: app.client_id,
    clientSecret: app.client_secret,
    // Webhooks are disabled, but the Backstage config schema still requires a value.
    webhookSecret: app.webhook_secret || crypto.randomBytes(24).toString('hex'),
    privateKey: app.pem,
  };
  const header =
    '# Generated by scripts/docs-studio/create-github-app.mjs. Contains secrets: do not commit.\n';
  fs.writeFileSync(outFile, header + YAML.stringify(credentials), {
    mode: 0o600,
  });
  fs.chmodSync(outFile, 0o600);
}

let finish;
const done = new Promise(resolve => (finish = resolve));

const server = http.createServer(async (req, res) => {
  const url = new URL(req.url ?? '/', 'http://127.0.0.1');
  const send = (status, body) => {
    res.writeHead(status, {
      'Content-Type': 'text/html; charset=utf-8',
      'Cache-Control': 'no-store',
    });
    res.end(body);
  };
  try {
    if (url.pathname === '/') {
      const manifest = JSON.stringify(buildManifest(server.address().port));
      const action = `https://github.com/organizations/${encodeURIComponent(
        org,
      )}/settings/apps/new?state=${state}`;
      return send(
        200,
        `<!doctype html><meta charset="utf-8"><title>Docs Studio GitHub App</title>
<p>Redirecting to GitHub to create the App in <b>${escapeHtml(org)}</b>…</p>
<form id="f" method="post" action="${escapeHtml(action)}">
<input type="hidden" name="manifest" value="${escapeHtml(manifest)}">
<button type="submit">Continue to GitHub</button></form>
<script>document.getElementById('f').submit()</script>`,
      );
    }
    if (url.pathname === '/callback') {
      const code = url.searchParams.get('code');
      if (!code || !safeEqual(url.searchParams.get('state') ?? '', state)) {
        return send(400, 'Invalid state or missing code. Start again.');
      }
      const app = await exchange(code);
      writeCredentials(app);
      send(
        200,
        '<!doctype html><meta charset="utf-8"><p>Done. You can close this tab and go back to the terminal.</p>',
      );
      return finish({ app, ok: true });
    }
    send(404, 'Not found');
  } catch (error) {
    send(500, 'Something went wrong. Check the terminal.');
    finish({ ok: false, error });
  }
});

const port = args.port ? Number(args.port) : 0;
await new Promise(resolve => server.listen(port, '127.0.0.1', resolve));
const localUrl = `http://127.0.0.1:${server.address().port}/`;
console.log(
  `Local server ready. Open this URL to create "${appName}" in ${org}:\n\n  ${localUrl}\n`,
);
if (!args['no-open']) {
  const opener =
    { darwin: 'open', win32: 'cmd' }[process.platform] ?? 'xdg-open';
  const openArgs =
    process.platform === 'win32' ? ['/c', 'start', '', localUrl] : [localUrl];
  if (run(opener, openArgs).status !== 0)
    console.log('(Could not open a browser automatically.)');
}
console.log(
  'Waiting for you to confirm the App in GitHub (10 minute timeout)...',
);

const timeout = setTimeout(
  () =>
    finish({ ok: false, error: new Error('Timed out waiting for GitHub.') }),
  10 * 60 * 1000,
);
const result = await done;
clearTimeout(timeout);
server.close();

if (!result.ok) fail(result.error.message);
const { app } = result;
const includePath = JSON.stringify(`./${path.relative(REPO_ROOT, outFile)}`);
console.log(`\nApp "${app.name}" created (id ${app.id}, slug ${app.slug}).`);
console.log(`Credentials written to ${outFile} (mode 0600).`);
console.log(`
Next steps:
  1. Install the App on the docs repo: ${app.html_url}/installations/new
     (select only your docs repository, the value of DOCS_STUDIO_REPOSITORY).
  2. If app-config.local.yaml does not exist, copy app-config.local.example.yaml
     to it. If it exists, find (or add, together with token: \${GITHUB_TOKEN}) the
     integrations.github entry with host: github.com and keep your other entries.
     In both cases make sure that entry has (the path is relative to the repo root,
     where app-config.local.yaml lives):
       apps:
         - $include: ${includePath}
  3. Apply the branch ruleset with the App id:
     node scripts/docs-studio/apply-ruleset.mjs --repo <org>/<repo> --app-id ${app.id}
`);
